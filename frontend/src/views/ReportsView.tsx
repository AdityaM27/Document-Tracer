import React from 'react';
import {
  Archive,
  ExternalLink,
  Download,
  FileText
} from 'lucide-react';
import { ReportItem } from '../types';

interface ReportsViewProps {
  reports: ReportItem[];
}

export const ReportsView: React.FC<ReportsViewProps> = ({ reports }) => {
  return (
    <div className="view-container">
      {/* View Header Card */}
      <div className="section-card">
        <h1 style={{ fontSize: '1.6rem', fontWeight: 700, color: 'var(--text-primary)', margin: '0 0 0.35rem' }}>
          Analysis Reports
        </h1>
        <p className="section-desc">
          Review, export, and inspect historical audit reports generated by the Document Tracer engine.
        </p>
      </div>

      {/* Reports Table Card */}
      <div className="section-card">
        <div className="section-header">
          <div>
            <div className="section-title">
              <Archive size={18} color="var(--primary-accent)" /> Historical Reports ({reports.length})
            </div>
            <div className="section-desc">Audit documents saved in local storage</div>
          </div>
        </div>

        {reports.length === 0 ? (
          <div className="empty-state">
            <p>No reports generated yet. Analyze a document to create an audit report.</p>
          </div>
        ) : (
          <table className="clean-table">
            <thead>
              <tr>
                <th>Document Filename</th>
                <th>Submission ID</th>
                <th>Analysis Date</th>
                <th>Overall Similarity</th>
                <th>AI Classification</th>
                <th style={{ textAlign: 'right' }}>Report Actions</th>
              </tr>
            </thead>
            <tbody>
              {reports.map((r) => {
                const simPct = Math.round(r.overallSimilarity * 100);
                const isHighSim = r.overallSimilarity > 0.5;
                const isMedSim = r.overallSimilarity > 0.25;

                return (
                  <tr key={r.id}>
                    <td>
                      <div style={{ display: 'flex', alignItems: 'center', gap: '0.45rem' }}>
                        <FileText size={15} color="var(--primary-accent)" />
                        <strong style={{ color: 'var(--text-primary)' }}>{r.filename}</strong>
                      </div>
                    </td>
                    <td>
                      <code>{r.id}</code>
                    </td>
                    <td style={{ color: 'var(--text-secondary)' }}>{r.timestamp}</td>
                    <td>
                      <span
                        className="clean-badge"
                        style={{
                          backgroundColor: isHighSim ? 'var(--error-light)' : isMedSim ? 'var(--warning-light)' : 'var(--success-light)',
                          color: isHighSim ? 'var(--error)' : isMedSim ? 'var(--warning)' : 'var(--success)',
                        }}
                      >
                        {simPct}%
                      </span>
                    </td>
                    <td>
                      <span className="pill pill-info">{r.aiLabel || 'Evaluated'}</span>
                    </td>
                    <td style={{ textAlign: 'right' }}>
                      <div style={{ display: 'inline-flex', gap: '0.45rem' }}>
                        <a
                          href={`/api/reports/${r.id}/html`}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="btn btn-sm btn-primary"
                          title="Open standalone HTML report"
                        >
                          <ExternalLink size={13} /> View HTML
                        </a>
                        <a
                          href={`/api/reports/${r.id}/json`}
                          download={`report_${r.id}.json`}
                          className="btn btn-sm btn-secondary"
                          title="Download structured JSON report"
                        >
                          <Download size={13} /> JSON
                        </a>
                      </div>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        )}
      </div>
    </div>
  );
};
